// Build-time metadata from the committed, pinned runtime; never evaluates a song.
import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';
import { fileURLToPath, pathToFileURL } from 'node:url';

export async function completionHeader(bundle) {
  const context = vm.createContext({
    __hostLog() {}, __hostSlider(_id, value) { return value; },
    __hostSignal() { return null; },
    performance: { now: () => 0 },
    console: { log() {}, warn() {}, error() {}, info() {}, debug() {} },
  });
  vm.runInContext(bundle, context, { timeout: 5000 });
  const words = JSON.parse(vm.runInContext(`JSON.stringify({
    globals: Object.keys(globalThis).filter(k => typeof globalThis[k] === 'function'),
    methods: Object.getOwnPropertyNames(__strudelModules['@strudel/core'].Pattern.prototype)
      .filter(k => typeof Object.getOwnPropertyDescriptor(__strudelModules['@strudel/core'].Pattern.prototype,k).value === 'function')
  })`, context, { timeout: 5000 }));
  const array = (name, values) => `static const char *const ${name}[] = {\n` +
    [...new Set(values)].filter(k => /^[a-zA-Z_$][\w$]*$/.test(k) && !k.startsWith('__') && k !== 'constructor')
      .sort().map(k => `    ${JSON.stringify(k)},`).join('\n') + '\n    NULL\n};\n';
  return '/* Generated by js/completions.mjs from the pinned runtime. */\n' +
    '#ifndef TOMPOUCE_JS_COMPLETIONS_H\n#define TOMPOUCE_JS_COMPLETIONS_H\n#include <stddef.h>\n' +
    array('strudel_global_words', words.globals) + array('strudel_method_words', words.methods) + '#endif\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const header = new URL('dist/completions.h', import.meta.url);
  const generated = await completionHeader(await readFile(new URL('dist/runtime.js', import.meta.url), 'utf8'));
  if (process.argv.includes('--check')) {
    if (await readFile(header, 'utf8') !== generated) throw new Error('Completion metadata is stale; run node js/completions.mjs');
    console.log('Pinned runtime completion metadata matches');
  } else await writeFile(fileURLToPath(header), generated);
}
