// Build-time reference from installed, lockfile-pinned Strudel JSDoc sources.
// No network, song evaluation, or documentation parsing in the running editor.
import {readFile, readdir, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root=new URL('./',import.meta.url);
const ascii=text=>text.replace(/\{@link\s+([^}]+)\}/g,'$1')
  .replace(/[‘’]/g,"'").replace(/[“”]/g,'"').replace(/[–—]/g,'-')
  .replace(/→/g,'->').replace(/♭/g,'b').replace(/♯/g,'#')
  .normalize('NFKD').replace(/[\u0300-\u036f]/g,'').replace(/[^\x20-\x7e\n]/g,' ');
const docs=new Map();
function collect(source,origin,override=false) {
    for(const match of source.matchAll(/\/\*\*([\s\S]*?)\*\//g)) {
      const lines=match[1].split('\n').map(line=>line.replace(/^\s*\* ?/,''));
      const fields={description:[]}; let tag='description';
      for(const line of lines) {
        const field=line.match(/^\s*@([\w]+)\s*(.*)$/);
        if(field) {tag=field[1];(fields[tag]??=[]).push(field[2]);}
        else (fields[tag]??=[]).push(line);
      }
      const following=source.slice(match.index+match[0].length,match.index+match[0].length+400);
      const inferred=following.match(/^\s*(?:export\s+)?(?:const|function)\s+([\w$]+)/)?.[1]
        ??following.match(/^\s*([\w$]+)\s*\(/)?.[1];
      const name=fields.name?.[0]?.trim()??inferred;
      const description=ascii(fields.description.join('\n').trim());
      if(!name || !/^[a-zA-Z$][\w$]*$/.test(name) || !description || fields.private) continue;
      const aliases=[...(fields.synonyms??[]),...(fields.alias??[])].join(' ').split(/[\s,]+/).filter(Boolean);
      const params=(fields.param??[]).filter(Boolean).map(ascii);
      const returns=ascii((fields.returns??fields.return??[]).join('\n').trim());
      const examples=ascii((fields.example??[]).join('\n').trim());
      const body=[description,params.length?'Parameters:\n'+params.join('\n'):'',
        returns?'Returns:\n'+returns:'',
        examples?'Examples:\n'+examples:''].filter(Boolean).join('\n\n');
      if(override || !docs.has(name)) docs.set(name,{name,aliases:aliases.join(' '),body,origin});
    }
}
for(const pkg of ['core','tonal','mini','transpiler']) {
  const base=new URL(`node_modules/@strudel/${pkg}/`,root);
  const manifest=JSON.parse(await readFile(new URL('package.json',base),'utf8'));
  if(manifest.version!=='1.2.6') throw new Error(`Reference requires pinned ${pkg} 1.2.6`);
  for(const file of (await readdir(base)).filter(name=>name.endsWith('.mjs')).sort()) {
    collect(await readFile(new URL(file,base),'utf8'),`@strudel/${pkg} 1.2.6 / ${file}`);
  }
}
for(const file of ['runtime.mjs','native-synth.mjs'])
  collect(await readFile(new URL(file,root),'utf8'),`Tompouce embedded runtime / ${file}`,true);
// The completion catalog includes Tompouce adapters and undocumented upstream
// exports. Keep them searchable while clearly distinguishing missing prose.
const catalog=await readFile(new URL('dist/completions.h',root),'utf8');
const vocabulary=new Set([...catalog.matchAll(/^\s*"([\w$]+)",/gm)].map(match=>match[1]));
// These source transforms/symbols are accepted by the embedded language but
// are not ordinary functions on globalThis or Pattern.prototype.
for(const name of ['K','S','sFreq','sGate']) vocabulary.add(name);
const candidates=[...docs.values()]
  .filter(doc=>vocabulary.has(doc.name) || doc.aliases.split(' ').some(name=>vocabulary.has(name)))
  .sort((a,b)=>Number(b.origin.startsWith('Tompouce embedded runtime'))-Number(a.origin.startsWith('Tompouce embedded runtime')));
const entries=[],covered=new Set();
for(const doc of candidates) {
  if(covered.has(doc.name)) continue;
  const aliases=doc.aliases.split(' ').filter(name=>name && !covered.has(name));
  entries.push({...doc,aliases:aliases.join(' ')});
  for(const name of [doc.name,...aliases]) covered.add(name);
}
for(const name of vocabulary) if(!covered.has(name)) entries.push({name,aliases:'',
  body:'Available in the embedded runtime. No authored documentation is available for this runtime name.',
  origin:'Embedded runtime vocabulary'});
entries.sort((a,b)=>a.name<b.name?-1:a.name>b.name?1:0);
const quote=text=>JSON.stringify(ascii(text));
const header='/* Generated by js/reference.mjs from Strudel 1.2.6 and Tompouce runtime JSDoc.\n'+
  ' * Copyright Strudel and Tompouce contributors. AGPL-3.0-or-later; see NOTICE and js/dist/licenses.txt. */\n'+
  '#ifndef TOMPOUCE_STRUDEL_REFERENCE_H\n#define TOMPOUCE_STRUDEL_REFERENCE_H\n'+
  'typedef struct { const char *name, *aliases, *body, *origin; } StrudelReference;\n'+
  'static const StrudelReference strudel_reference[] = {\n'+entries.map(doc=>
    `    {${[doc.name,doc.aliases,doc.body,doc.origin].map(quote).join(', ')}},`).join('\n')+
  '\n};\n#endif\n';
const target=new URL('dist/reference.h',root);
if(process.argv.includes('--check')) {
  if(await readFile(target,'utf8')!==header) throw new Error('Reference metadata is stale; run node js/reference.mjs');
} else await writeFile(fileURLToPath(target),header);
console.log(`${entries.length} offline reference entries (${entries.filter(doc=>doc.origin!=='Embedded runtime vocabulary').length} documented)`);
